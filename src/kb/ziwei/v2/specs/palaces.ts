const STAR_HEAD = /^(紫微|天機|太陽|武曲|天同|廉貞|天府|太陰|貪狼|巨門|天相|天梁|七殺|破軍|文昌|文曲|左輔|右弼|祿存|擎羊|陀羅|羊陀|羊鈴|火星|鈴星|火鈴星|魁鉞|天魁|斗君|君逢)/;
const plain = (c: string) => c.replace(/〔(?:疑字|校)：(.)〕/g, "$1").replace(/〔缺字〕/g, "□").replace(/[〈〉]/g, "");
/** 逐欄掃描主文（不含補轉錄欄組）：以星名開頭的欄為一條，續行併入；已被上面手寫規則使用的欄不重複登錄。 */
export function historicalColumns(used: Set<string>): ClauseSpec[] {
  const out: ClauseSpec[] = [];
  for (const sec of HIST_SECTIONS) {
    let on = false, n = 0;
    for (const leaf of sec.leafs) {
      const L = GUANGYI_PAGES.leaves.find(l => l.leaf === leaf);
      if (!L) continue;
      let cur: { leaf: string; text: string } | null = null;
      const flush = () => {
        if (!cur || !cur.text || /□/.test(cur.text)) { cur = null; return; }
        const head = cur.text.match(STAR_HEAD)?.[1] ?? "";
        const isDou = head === "斗君" || head === "君逢";
        if (!used.has(cur.text)) out.push({
          id: `GY_P_${sec.code}_H${++n}`, leaf: cur.leaf, section: `${sec.name}・${head}`, quote: cur.text,
          translation: isDou ? "斗君（流月）過此宮之吉凶；本 App 客觀排盤沒有斗君。" : `${sec.name}宮${head}條：${sec.why}之古代斷語，只保留原文，不作判讀。`,
          title: `${sec.name}・${head}（只保留原文）`, kind: "palace", when: null, pendingReason: (isDou ? "requiresChartExtension" : "historicalOnly") as PendingReason,
        });
        cur = null;
      };
      for (const s of L.strips) {
        if (s.strip >= SUPPLEMENT_BASE) continue;
        for (const col of s.columns) {
          const t = plain(col).trim();
          if (!t) continue;
          if (t === sec.start) { on = true; continue; }
          if (sec.end && t === sec.end) { flush(); on = false; continue; }
          if (!on) continue;
          if (STAR_HEAD.test(t)) { flush(); cur = { leaf, text: t }; }
          else if (cur) cur.text += t;
        }
      }
      flush();
    }
  }
  return out;
}
