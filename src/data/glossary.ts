const byTerm = new Map(GLOSSARY.map(g => [g.term, g]));

/** 依據上的 term 可能是複合詞（如「日支逢沖」「化祿」「脫胎要火」），盡量對應到辭典條目。 */
export function lookupTerm(term: string): GlossaryEntry | null {
  if (byTerm.has(term)) return byTerm.get(term)!;
  const m = term.match(/^(年支|月支|日支|時支)(逢沖|六合|三合|逢刑)$/);
  if (m) return byTerm.get(m[2].replace("逢", "")) ?? null;
  if (term === "體用生剋") return byTerm.get("體用生剋")!;
  return null;
}
